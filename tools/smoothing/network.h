// Модель отправки и доставки пакетов по UDP.
#pragma once

#include <vector>

#include "trajectory.h"

// Все числовые параметры симуляции.
struct Config {
    double rate = 20.0;         // частота отправки, пакетов в секунду реального времени
    double warp = 1.0;          // во сколько раз симуляционное время быстрее реального
    double lossPercent = 0.0;   // вероятность потери пакета, %
    double latencyMs = 1.0;     // базовая задержка доставки, мс реального времени
    double jitterMs = 5.0;      // разброс задержки (равномерно от 0 до значения), мс
    double delayMs = 100.0;     // задержка интерполяции на клиенте, мс реального времени
    unsigned seed = 1;          // начальное значение генератора случайных чисел
    double duration = 120.0;    // длительность в секундах симуляционного времени
    Profile profile = Profile::Pilot;  // профиль эталонного движения
};

// Доставленный пакет: состояние хоста и момент прихода на клиент.
struct Packet {
    State state;
    double arrivalWall = 0.0;  // реальное время прихода, с
};

// Возвращает пакеты, дошедшие до клиента, в порядке прихода
// (из-за джиттера порядок по симуляционному времени может нарушаться).
std::vector<Packet> simulateNetwork(const Trajectory& truth, const Config& config);
